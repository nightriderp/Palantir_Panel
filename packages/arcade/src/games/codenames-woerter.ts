/** Alle Begriffe einer Kategorie oder aller Kategorien. */
export function codenamesWoerter(kategorie: CodenamesKategorie | 'alle'): string[] {
  const quellen =
    kategorie === 'alle'
      ? CODENAMES_KATEGORIEN
      : CODENAMES_KATEGORIEN.filter((k) => k.id === kategorie);
  return quellen.flatMap((k) => [...k.woerter]);
}
